// Captura do clipboard: Timer de 0,5 s no changeCount (o macOS não avisa quando o clipboard muda) + dedupe por
// SHA-256. Dividido em duas partes para testar sem timer: `foto` lê o pasteboard (thread principal) e `processar`
// classifica, filtra e grava (pode rodar fora da principal).
import AppKit
import CryptoKit
import ImageIO
import UniformTypeIdentifiers

public final class Coletor {
    /// Tipos que dizem "não guarde" (convenção nspasteboard.org, gerenciadores de senha, Universal Clipboard).
    public static let tiposIgnorados: Set<String> = [
        "org.nspasteboard.ConcealedType",          // senha (gerenciadores de senha, Keychain)
        "org.nspasteboard.TransientType",          // temporário
        "org.nspasteboard.AutoGeneratedType",      // gerado por app, não pelo usuário
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "com.agilebits.onepassword-osx",
        "com.agilebits.onepassword4",
        "com.agilebits.onepassword7",
        "com.apple.is-remote-clipboard",           // veio do iPhone pelo Universal Clipboard
    ]
    /// Convenção nspasteboard.org: bundle id do app que copiou.
    public static let tipoOrigem = "org.nspasteboard.source"
    /// Marca que o próprio Colar põe ao colar um item: a captura só sobe o item, não cria outro.
    public static let tipoColar = "app.colar.item-id"
    /// Teto por item (imagem gigante, vídeo copiado no Finder vem como file-url, não como dado).
    public static let maxBytes = 64 * 1024 * 1024

    public struct Foto {
        public let changeCount: Int
        public let itens: [[(uti: String, dados: Data)]]
        public let appDaFrente: NSRunningApplication?
        /// `pasteboard.types`: único lugar onde tipos de nome legado (com espaço, ex. "Pasteboard generator type")
        /// aparecem com o nome; nos itens eles viram `dyn.…` (conferido no macOS 27). O filtro precisa olhar aqui também.
        public let tiposGerais: [String]
        public init(changeCount: Int, itens: [[(uti: String, dados: Data)]], appDaFrente: NSRunningApplication?,
                    tiposGerais: [String] = []) {
            self.changeCount = changeCount; self.itens = itens; self.appDaFrente = appDaFrente; self.tiposGerais = tiposGerais
        }
    }

    public enum Decisao: Equatable {
        case gravado(Historico.Resultado), ignorado(String), colarProprio(String), vazio
    }

    public let historico: Historico
    public let pasteboard: NSPasteboard
    public var pausado = false
    public var appsIgnorados: Set<String> = []
    private var ultimoChange: Int
    private var timer: Timer?
    private let fila = DispatchQueue(label: "app.colar.coletor")
    public var aoMudar: ((Decisao) -> Void)?

    public init(historico: Historico, pasteboard: NSPasteboard = .general) {
        self.historico = historico
        self.pasteboard = pasteboard
        ultimoChange = pasteboard.changeCount
    }

    public func iniciar(intervalo: TimeInterval = 0.5) {
        ultimoChange = pasteboard.changeCount
        let t = Timer(timeInterval: intervalo, repeats: true) { [weak self] _ in self?.verificar() }
        t.tolerance = intervalo / 5
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    public func parar() { timer?.invalidate(); timer = nil }

    /// Chamado pelo timer na thread principal.
    public func verificar() {
        guard pasteboard.changeCount != ultimoChange else { return }
        ultimoChange = pasteboard.changeCount
        guard !pausado, let foto = foto() else { return }
        fila.async { [weak self] in
            guard let self else { return }
            let d = self.processar(foto)
            DispatchQueue.main.async { self.aoMudar?(d) }
        }
    }

    /// Lê todos os itens e tipos do pasteboard agora.
    public func foto() -> Foto? {
        let itens = (pasteboard.pasteboardItems ?? []).map { item in
            item.types.compactMap { t -> (uti: String, dados: Data)? in
                guard let d = item.data(forType: t) else { return nil }
                return (t.rawValue, d)
            }
        }
        return Foto(changeCount: pasteboard.changeCount, itens: itens, appDaFrente: NSWorkspace.shared.frontmostApplication,
                    tiposGerais: (pasteboard.types ?? []).map(\.rawValue))
    }

    /// Classifica, filtra e grava. Síncrono (os checks chamam direto).
    public func processar(_ foto: Foto, agora: Date = Date()) -> Decisao {
        let todos = foto.itens.flatMap { $0 }
        guard !todos.isEmpty else { return .vazio }
        let utis = Set(todos.map(\.uti)).union(foto.tiposGerais)

        if let ig = utis.first(where: Self.tiposIgnorados.contains) { return .ignorado("tipo \(ig)") }
        if let marca = todos.first(where: { $0.uti == Self.tipoColar }), let id = String(data: marca.dados, encoding: .utf8) {
            try? historico.marcarUsado(id, agora: agora)
            return .colarProprio(id)
        }
        let origem = todos.first(where: { $0.uti == Self.tipoOrigem }).flatMap { String(data: $0.dados, encoding: .utf8) }
        let bundle = origem ?? foto.appDaFrente?.bundleIdentifier
        if let bundle, appsIgnorados.contains(bundle) { return .ignorado("app \(bundle)") }
        let nomeApp = bundle.flatMap { b in
            NSRunningApplication.runningApplications(withBundleIdentifier: b).first?.localizedName
                ?? NSWorkspace.shared.urlForApplication(withBundleIdentifier: b)?.deletingPathExtension().lastPathComponent
        } ?? foto.appDaFrente?.localizedName

        guard let c = Self.classificar(foto.itens) else { return .vazio }
        // Tipos dinâmicos (dyn.*) e a origem não ajudam a recolar e só ocupam espaço.
        var reps: [Representacao] = []
        var total = 0
        for (i, item) in foto.itens.enumerated() {
            for r in item where !r.uti.hasPrefix("dyn.") && r.uti != Self.tipoOrigem {
                total += r.dados.count
                reps.append(Representacao(indicePb: i, uti: r.uti, dados: r.dados))
            }
        }
        guard total <= Self.maxBytes else { return .ignorado("grande demais (\(total) bytes)") }
        do {
            let r = try historico.gravar(tipo: c.tipo, texto: c.texto, checksum: c.checksum, representacoes: reps,
                                         app: bundle.map { ($0, nomeApp ?? $0) }, tamanho: c.tamanho,
                                         largura: c.largura, altura: c.altura, miniatura: c.miniatura, agora: agora)
            return .gravado(r)
        } catch {
            return .ignorado("erro ao gravar: \(error)")
        }
    }

    // MARK: classificação

    public struct Classificacao {
        public let tipo: TipoItem
        public let texto: String?
        public let checksum: String
        public let tamanho: Int
        public var largura: Int? = nil
        public var altura: Int? = nil
        public var miniatura: Data? = nil
    }

    static let utiTexto = ["public.utf8-plain-text", "NSStringPboardType", "public.utf16-plain-text"]
    static let utiImagem = ["public.png", "public.tiff", "public.jpeg", "public.heic", "com.compuserve.gif"]

    /// Decide o tipo pelo conteúdo principal. O checksum usa só o conteúdo principal, para o mesmo texto copiado de
    /// apps diferentes (um com HTML junto, outro sem) virar um item só.
    public static func classificar(_ itens: [[(uti: String, dados: Data)]]) -> Classificacao? {
        func dado(_ utis: [String], em item: [(uti: String, dados: Data)]) -> (uti: String, dados: Data)? {
            for u in utis { if let r = item.first(where: { $0.uti == u }) { return r } }
            return nil
        }
        let primeiro = itens.first ?? []

        // Arquivos (Finder): um file-url por item do pasteboard.
        let urls = itens.compactMap { dado(["public.file-url"], em: $0) }.compactMap {
            URL(dataRepresentation: $0.dados, relativeTo: nil)
        }
        if !urls.isEmpty {
            let caminhos = urls.map(\.path)
            return Classificacao(tipo: .arquivo, texto: urls.map(\.lastPathComponent).joined(separator: "\n"),
                                 checksum: "arquivo:" + sha(Data(caminhos.joined(separator: "\n").utf8)), tamanho: urls.count)
        }

        // Imagem (print, imagem copiada do navegador).
        if let img = dado(utiImagem, em: primeiro) {
            let (l, a, mini) = dimensoesEMiniatura(img.dados)
            let alt = dado(utiTexto, em: primeiro).flatMap { String(data: $0.dados, encoding: .utf8) }
            return Classificacao(tipo: .imagem, texto: alt, checksum: "imagem:" + sha(img.dados), tamanho: img.dados.count,
                                 largura: l, altura: a, miniatura: mini)
        }

        guard let s = dado(utiTexto, em: primeiro).flatMap({ String(data: $0.dados, encoding: .utf8) }),
              !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return nil }
        let limpo = s.trimmingCharacters(in: .whitespacesAndNewlines)
        let ck = sha(Data(s.utf8))

        // Cor: 6 dígitos hex, com ou sem # .
        if limpo.range(of: #"^#?[0-9A-Fa-f]{6}$"#, options: .regularExpression) != nil {
            let hex = "#" + limpo.replacingOccurrences(of: "#", with: "").uppercased()
            return Classificacao(tipo: .cor, texto: hex, checksum: "cor:" + hex, tamanho: hex.count)
        }
        // Link: uma URL http(s) sozinha.
        if !limpo.contains(where: \.isWhitespace), let u = URL(string: limpo), let esq = u.scheme?.lowercased(),
           ["http", "https"].contains(esq), u.host != nil {
            return Classificacao(tipo: .link, texto: limpo, checksum: "link:" + ck, tamanho: limpo.count)
        }
        let rico = primeiro.contains { ["public.rtf", "public.html", "com.apple.flat-rtfd", "com.apple.webarchive"].contains($0.uti) }
        return Classificacao(tipo: rico ? .richText : .texto, texto: s, checksum: "texto:" + ck, tamanho: s.count)
    }

    static func sha(_ d: Data) -> String { Historico.sha256(d) }

    /// Largura e altura em pixels e um PNG de até 640 px no lado maior para o cartão.
    static func dimensoesEMiniatura(_ d: Data) -> (Int?, Int?, Data?) {
        guard let src = CGImageSourceCreateWithData(d as CFData, nil) else { return (nil, nil, nil) }
        let props = CGImageSourceCopyPropertiesAtIndex(src, 0, nil) as? [CFString: Any]
        let l = props?[kCGImagePropertyPixelWidth] as? Int
        let a = props?[kCGImagePropertyPixelHeight] as? Int
        let opcoes: [CFString: Any] = [kCGImageSourceCreateThumbnailFromImageAlways: true,
                                      kCGImageSourceThumbnailMaxPixelSize: 640,
                                      kCGImageSourceCreateThumbnailWithTransform: true]
        guard let mini = CGImageSourceCreateThumbnailAtIndex(src, 0, opcoes as CFDictionary) else { return (l, a, nil) }
        let saida = NSMutableData()
        guard let dest = CGImageDestinationCreateWithData(saida, UTType.png.identifier as CFString, 1, nil) else { return (l, a, nil) }
        CGImageDestinationAddImage(dest, mini, nil)
        return CGImageDestinationFinalize(dest) ? (l, a, saida as Data) : (l, a, nil)
    }
}
